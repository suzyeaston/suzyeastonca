const {chromium} = require('@playwright/test');
const fs = require('node:fs');
const assert = require('node:assert/strict');

(async () => {
  const browser = await chromium.launch({headless:true});
  const page = await browser.newPage({viewport:{width:1280,height:900}});
  const errors=[];
  page.on('pageerror', error=>errors.push(error.message));
  const php = fs.readFileSync('template-yvr-radio.php','utf8').replace(/<\?php[\s\S]*?\?>/g,'');
  const css = fs.readFileSync('assets/css/yvr-radio.css','utf8');
  const html = '<!DOCTYPE html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><style>body{margin:0;background:#060d12;min-height:100vh}'+css+'</style></head><body>'+php+'</body></html>';
  await page.route('https://radio.test/**',route=>route.fulfill({contentType:'text/html',body:html}));
  await page.goto('https://radio.test/');
  await page.evaluate(() => {
    window.testTransmitter = {online:true,listeners:3};
    window.fetch = async () => ({ok:true,json:async()=>window.testTransmitter});
    const audio = HTMLMediaElement.prototype;
    audio.play = function() {this._paused=false;return Promise.resolve();};
    audio.pause = function() {this._paused=true;};
    audio.load = function() {};
    Object.defineProperty(audio,'paused',{get() {return this._paused!==false;}});
    document.querySelector('[data-pirate-radio]').dataset.streamUrl='https://relay.test/live.mp3';
    document.querySelector('[data-pirate-radio]').dataset.statusUrl='https://relay.test/status.json';
  });
  await page.addScriptTag({content:fs.readFileSync('assets/js/yvr-radio.js','utf8')});
  const root=page.locator('[data-pirate-radio]');
  const action=page.locator('[data-radio-play]');
  await page.waitForFunction(()=>document.querySelector('[data-pirate-radio]').dataset.broadcastState==='online');
  assert.match(await page.locator('[data-radio-status-text]').textContent(),/ON AIR/);
  assert.equal(await page.locator('[data-radio-listeners]').textContent(),'3 listeners connected');
  assert.equal(await action.isEnabled(),true);
  assert.equal(await root.getAttribute('data-player-state'),'stopped'); // No autoplay.
  await action.click();
  await page.waitForFunction(()=>document.querySelector('[data-pirate-radio]').dataset.playerState==='playing');
  assert.equal(await action.textContent(),'Pause');
  await page.locator('[data-radio-volume]').fill('0.4');
  assert.equal(await page.locator('[data-radio-volume-value]').textContent(),'40%');
  await action.click();
  assert.equal(await root.getAttribute('data-player-state'),'paused');
  await action.click();
  await page.waitForFunction(()=>document.querySelector('[data-pirate-radio]').dataset.playerState==='playing');
  await page.locator('[data-radio-stop]').click();
  assert.equal(await root.getAttribute('data-player-state'),'stopped');
  await page.evaluate(()=>{window.testTransmitter={online:false,listeners:0};document.dispatchEvent(new Event('visibilitychange'));});
  await page.waitForFunction(()=>document.querySelector('[data-pirate-radio]').dataset.broadcastState==='offline');
  assert.match(await page.locator('[data-radio-status-text]').textContent(),/OFF AIR/);
  assert.equal(await action.isDisabled(),true);
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.screenshot({path:'/tmp/suzy-pirate-radio-mobile.png',fullPage:true});
  assert.deepEqual(errors,[]);
  await page.close();
  const second=await browser.newPage();
  await second.route('https://radio.test/**',route=>route.fulfill({contentType:'text/html',body:html}));
  await second.goto('https://radio.test/');
  await second.addScriptTag({content:fs.readFileSync('assets/js/yvr-radio.js','utf8')});
  assert.equal(await second.locator('[data-pirate-radio]').getAttribute('data-broadcast-state'),'unconfigured');
  assert.equal(await second.locator('[data-radio-play]').isDisabled(),true);
  assert.match(await second.locator('[data-radio-status-text]').textContent(),/NOT CONNECTED/);
  await browser.close();
  console.log('PASS: independent pirate receiver, real status, offline safeguards, play/pause/stop, volume, no autoplay, mobile and unconfigured mode.');
})().catch(error=>{console.error(error);process.exitCode=1;});
